#!/usr/bin/env python3
"""G2 generated-code identity guard (G3 increment 3).

The G2 translator (tools/aot/aot_translate.py) fingerprints ITSELF into every
generated file: `sha = sha256(flat || manifest || translator bytes || config)`.
That is deliberate provenance -- ANY change to the translator must change the
fingerprint -- but it means a translator edit always perturbs exactly two lines
of every generated G2 .c file:

  * the header comment line  ` * source sha256: <hex>`
  * the AotImage field line  `    "<hex>",`

This guard strips EXACTLY those two provenance-derived lines and compares the
SHA-256 of the remainder against a committed baseline. Everything else in the
generated code -- blocks, helpers, ranges, thunk metadata, the subset id and the
ABI/layout constants -- must stay byte-identical, which is the real requirement
behind "G2 output must not change".

Usage:
  g2_gen_identity_check.py --dir <aot_gen dir> --baseline <file>
  g2_gen_identity_check.py --dir <aot_gen dir> --baseline <file> --write

--write regenerates the baseline (only legitimate from an UNCHANGED translator:
the baseline is the fingerprint-free hash of the current G2 output).
"""

import argparse
import hashlib
import os
import re
import sys

# Provenance-derived lines, matched exactly (nothing else is stripped).
PROVENANCE_LINES = (
    # \r? because the generated files keep the host's CRLF line endings.
    re.compile(rb"^ \* source sha256: [0-9a-f]{64}\r?$"),
    re.compile(rb'^    "[0-9a-f]{64}",\r?$'),
)


def stripped_digest(path):
    """SHA-256 of the file with the two provenance lines removed."""
    with open(path, "rb") as f:
        raw = f.read()
    kept = []
    dropped = 0
    for line in raw.split(b"\n"):
        if any(pat.match(line) for pat in PROVENANCE_LINES):
            dropped += 1
            continue
        kept.append(line)
    if dropped != 2:
        raise SystemExit(
            "%s: expected exactly 2 provenance lines, dropped %d "
            "(the generated-file format changed; re-derive the baseline "
            "deliberately)" % (path, dropped))
    return hashlib.sha256(b"\n".join(kept)).hexdigest()


def collect(gen_dir):
    """Every G2 generated translation unit: aot_gen/*.c (the g3/ subdirectory
    holds descriptor tables generated by aot_module.py, not translator output)."""
    out = []
    for name in sorted(os.listdir(gen_dir)):
        if not name.endswith(".c"):
            continue
        out.append((name, os.path.join(gen_dir, name)))
    if not out:
        raise SystemExit("%s: no generated .c files found" % gen_dir)
    return out


def read_baseline(path):
    table = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            digest, name = line.split(None, 1)
            table[name.strip()] = digest
    return table


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dir", required=True, help="the aot_gen directory")
    ap.add_argument("--baseline", required=True,
                    help="baseline file (generated with --write)")
    ap.add_argument("--write", action="store_true",
                    help="(re)write the baseline from the CURRENT output")
    args = ap.parse_args(argv)

    files = collect(args.dir)
    current = {name: stripped_digest(path) for name, path in files}

    if args.write:
        with open(args.baseline, "w", encoding="utf-8", newline="\n") as f:
            f.write("# G2 generated-code identity baseline (G3 increment 3).\n"
                    "# SHA-256 of each aot_gen/*.c with the two "
                    "provenance-derived lines removed\n"
                    "# (translator fingerprint), so a translator edit cannot "
                    "hide a semantic change.\n"
                    "# Regenerate ONLY from an unchanged translator.\n")
            for name, _path in files:
                f.write("%s  %s\n" % (current[name], name))
        print("g2_gen_identity_check: wrote %d entries to %s"
              % (len(current), args.baseline))
        return 0

    baseline = read_baseline(args.baseline)
    failures = 0
    for name, digest in sorted(current.items()):
        want = baseline.get(name)
        if want is None:
            print("FAIL %s: not in the baseline (new G2 output?)" % name)
            failures += 1
        elif want != digest:
            print("FAIL %s: stripped digest %s != baseline %s"
                  % (name, digest[:16], want[:16]))
            failures += 1
    for name in sorted(baseline):
        if name not in current:
            print("FAIL %s: in the baseline but no generated file" % name)
            failures += 1
    if failures:
        print("g2_gen_identity_check: %d mismatch(es): the G2 translation "
              "output changed beyond the two provenance lines" % failures)
        return 2
    print("g2_gen_identity_check: %d G2 files byte-identical apart from the "
          "two provenance lines" % len(current))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
