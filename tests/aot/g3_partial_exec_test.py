#!/usr/bin/env python3
"""NATIVE execution proof of the partial-AOT unsupported trap.

The emitted block is compiled and called directly (no loader, no Program, no
interpreter): the trap must return AOT_EXIT_FAULT with

  * code  AOT_FAULT_UNSUPPORTED_INSN (16)   -- NOT BAD_STATE,
  * src   exactly the faulting guest PC,
  * status the offline metadata index,
  * target/next_pc/site_pc the same PC,
  * AotGuestState BYTE-IDENTICAL (GPR/SP/NZCV/FP/V/TPIDR) and no memory access.

Two generator mutants are COMPILED from the same emitted C and must be
rejected by the same runner (infrastructure failures are never counted as a
rejection):
  * NOP replacement  -> no fault / fallthrough,
  * BAD_STATE code   -> wrong fault code.

Exit: 0 pass, 2 semantic failure, 1 infrastructure.
"""

import argparse
import glob
import json
import os
import re
import subprocess
import sys
import tempfile

UNDECODABLE = 0xFFFFFFFF
BASE = 0x1000000000
ENTRY = BASE                      # mov x0,#1 is a valid prefix in this block
TRAP = BASE + 4                   # ... then the undecodable word traps


def find_vcvars():
    hits = sorted(glob.glob(
        r"C:/Program Files/Microsoft Visual Studio/*/*/VC/Auxiliary/Build/vcvars64.bat"))
    return hits[-1] if hits else None


RUNNER = r'''/* Generated by tests/aot/g3_partial_exec_test.py -- synthetic. */
#include <stdio.h>
#include <string.h>
#include "aot_runtime.h"
#include "__IMG__"

#define FAULT_PC __PCL__
#define ENTRY_PC __ENTRYL__

int main(void)
{
    AotGuestState s;
    AotGuestState before;
    AotRuntime rt;
    AotExit e;
    unsigned i;

    memset(&s, 0, sizeof s);
    memset(&rt, 0, sizeof rt);
    for (i = 0u; i < 31u; i++) {
        s.x[i] = 0x1111000000000000ull + i;
    }
    s.sp = 0x2000000000ull;
    s.nzcv = 0xA0000000u;
    s.pc = 0xDEADBEEFull;
    s.fpcr = 0x00000100u;
    s.fpsr = 0x00000010u;
    s.tpidr = 0x1234ull;
    s.tpidrro = 0x5678ull;
    before = s;

    e = aot_blk___ENTRYH__(&s, &rt);
    if (e != AOT_EXIT_FAULT) {
        printf("FAIL: exit %d, expected AOT_EXIT_FAULT (6)\n", (int)e);
        return 2;
    }
    if (rt.fault != AOT_FAULT_UNSUPPORTED_INSN) {
        printf("FAIL: fault %u, expected AOT_FAULT_UNSUPPORTED_INSN (16)\n",
               (unsigned)rt.fault);
        return 2;
    }
    if (rt.fault_src != FAULT_PC || rt.fault_target != FAULT_PC ||
        rt.next_pc != FAULT_PC || rt.site_pc != FAULT_PC) {
        printf("FAIL: fault src/target/next/site 0x%llx/0x%llx/0x%llx/"
               "0x%llx, expected 0x%llx\n",
               (unsigned long long)rt.fault_src,
               (unsigned long long)rt.fault_target,
               (unsigned long long)rt.next_pc,
               (unsigned long long)rt.site_pc,
               (unsigned long long)FAULT_PC);
        return 2;
    }
    if (rt.fault_status != 0) {
        printf("FAIL: status %lld, expected 0\n", (long long)rt.fault_status);
        return 2;
    }
    /* The valid prefix `mov x0,#1` must have taken effect ... */
    if (s.x[0] != 1ull) {
        printf("FAIL: valid prefix effect lost (x0=0x%llx, expected 1)\n",
               (unsigned long long)s.x[0]);
        return 2;
    }
    /* ... and nothing ELSE may have changed. */
    before.x[0] = 1ull;
    if (memcmp(&s, &before, sizeof s) != 0) {
        printf("FAIL: AotGuestState changed beyond the prefix "
               "(GPR/SP/NZCV/FP/V/TPIDR)\n");
        return 2;
    }
    printf("PASS: partial trap code=16 src=0x%llx status=0 prefix=x0=1 "
           "rest-unchanged\n", (unsigned long long)rt.fault_src);
    return 0;
}
'''


def fail(msg):
    print("FAIL: " + msg)
    return 2


def infrastructure(msg):
    print("infrastructure: " + msg)
    return 1


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--tools", default="tools/aot")
    ap.add_argument("--repo", default=".")
    args = ap.parse_args(argv)
    python = sys.executable
    vcvars = find_vcvars()
    if vcvars is None:
        return infrastructure("vcvars64.bat not found")
    work = tempfile.mkdtemp(prefix="aot_partial_exec_")
    tools = os.path.abspath(args.tools)
    repo = os.path.abspath(args.repo)

    raw = b"".join(w.to_bytes(4, "little")
                   for w in (0xD2800020, UNDECODABLE, 0xD65F03C0))
    lay = {"name": "synthetic", "image_size": len(raw), "bss_size": 0,
           "bss_start": len(raw), "bss_end": len(raw),
           "text": [0, len(raw)], "ro": [len(raw), len(raw)],
           "data": [len(raw), len(raw)], "dynsym_count": 0}
    import hashlib
    lay["sha256"] = hashlib.sha256(raw).hexdigest()
    flat = os.path.join(work, "flat.bin")
    open(flat, "wb").write(raw)
    lp = os.path.join(work, "layout.json")
    json.dump(lay, open(lp, "w"))
    ep = os.path.join(work, "entries.json")
    json.dump([ENTRY], open(ep, "w"))

    img = os.path.join(work, "img_partial.c")
    meta = os.path.join(work, "img_partial.meta.json")
    p = subprocess.run([python, os.path.join(tools, "aot_translate.py"),
                        "--module", "--partial", "--flat", flat,
                        "--layout", lp, "--guest-base", "0x%x" % BASE,
                        "--entries", ep, "--name", "synthetic",
                        "--out", img, "--meta-out", meta],
                       capture_output=True, text=True)
    if p.returncode != 0:
        return infrastructure("translation failed: " + p.stderr)
    doc = json.load(open(meta))
    unsup = doc["unsupported"]
    if len(unsup) != 1 or int(unsup[0]["pc"], 16) != TRAP:
        return fail("metadata does not pin the trap to 0x%x: %r" % (TRAP, unsup))
    blocks = doc["blocks"]
    # end_pc is the encoded-word span (trap PC + 4), per the metadata contract;
    # it does not claim the trap word was executed.
    if len(blocks) != 1 or int(blocks[0]["pc"], 16) != ENTRY             or int(blocks[0]["end_pc"], 16) != TRAP + 4:
        return fail("metadata block does not span prefix..trap: %r" % (blocks,))

    text = open(img).read()
    mutants = {
        "real": text,
        "nop": text.replace(
            "return aot_fault_unsupported(rt, 0x%xull, (int64_t)0u);" % TRAP,
            "return AOT_EXIT_FALLTHROUGH;"),
        "badstate": text.replace(
            "rt->fault = AOT_FAULT_UNSUPPORTED_INSN;",
            "rt->fault = AOT_FAULT_BAD_STATE;"),
    }
    # Drop the prefix-effect statement from the emitted block. Exactly one
    # aot_set_zr(...) line for x0 exists (the mov x0,#1 prefix).
    drop_re = re.compile(r"^\s*aot_set_zr\(s, 0u, .*\);\s*$", re.M)
    if len(drop_re.findall(text)) != 1:
        return fail("could not locate exactly one prefix assignment in the "
                    "emitted block")
    mutants["drop_prefix"] = drop_re.sub("", text, count=1)
    if mutants["nop"] == text or mutants["badstate"] == text             or mutants["drop_prefix"] == text:
        return fail("could not construct the generator mutants")

    results = {}
    for tag, src in mutants.items():
        d = os.path.join(work, tag)
        os.makedirs(d)
        imgp = os.path.join(d, "img_partial.c")
        open(imgp, "w").write(src)
        runner = os.path.join(d, "runner.c")
        open(runner, "w").write(
            RUNNER.replace("__IMG__", "img_partial.c").replace(
                "__PCL__", "0x%xull" % TRAP).replace(
                "__ENTRYL__", "0x%xull" % ENTRY).replace(
                "__ENTRYH__", "%x" % ENTRY))
        exe = os.path.join(d, "runner.exe")
        bat = os.path.join(d, "build.bat")
        with open(bat, "w", encoding="ascii") as f:
            f.write('@call "%s" >nul\r\n' % vcvars.replace("/", "\\"))
            f.write('cl /nologo /W4 /O2 /std:c11 /D_CRT_SECURE_NO_WARNINGS '
                    '/Fo:"%s\\\\" /I"%s" /I"%s" /Fe:"%s" "%s"\r\n'
                    % (d.replace("/", "\\"),
                       os.path.join(repo, "src", "aot").replace("/", "\\"),
                       os.path.join(repo, "src").replace("/", "\\"),
                       exe.replace("/", "\\"), runner.replace("/", "\\")))
        cp = subprocess.run([bat], capture_output=True, text=True)
        if cp.returncode != 0:
            return infrastructure("compile failed for %s: %s"
                                  % (tag, cp.stdout + cp.stderr))
        rp = subprocess.run([exe], capture_output=True, text=True)
        results[tag] = (rp.returncode, rp.stdout.strip())
        print("%s: exit=%d %s" % (tag, rp.returncode, rp.stdout.strip()))

    if results["real"][0] != 0:
        return fail("unmutated partial trap was not accepted: %s"
                    % results["real"][1])
    if results["nop"][0] != 2 or "expected AOT_EXIT_FAULT" \
            not in results["nop"][1]:
        return fail("NOP mutant was not rejected by the native runner: %r"
                    % (results["nop"],))
    if results["badstate"][0] != 2 or "fault 6" not in results["badstate"][1]:
        return fail("BAD_STATE mutant was not rejected by the native runner: %r"
                    % (results["badstate"],))
    if results["drop_prefix"][0] != 2 or "valid prefix effect lost"             not in results["drop_prefix"][1]:
        return fail("DROP_PREFIX mutant was not rejected by the native runner: %r"
                    % (results["drop_prefix"],))
    print("partial trap: native code=16 exact src/status, prefix applied, rest "
          "unchanged; NOP, BAD_STATE and DROP_PREFIX mutants compiled and "
          "rejected")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
