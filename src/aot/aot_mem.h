/*
 * G2 AOT proof: bounds-checked byte-addressable guest memory arena.
 *
 * Deliberately NOT the Mac model. The Mac loader maps guest virtual addresses
 * to host pointers and dereferences them directly. Here every access goes
 * through an explicit guest base + size and is performed with memcpy on
 * unsigned little-endian helpers. There is no cast from a guest address to a
 * host pointer and no out-of-bounds dereference.
 *
 * Alignment policy: A64 normal (non-device) accesses may be unaligned; the
 * helpers therefore permit unaligned offsets and implement them with memcpy,
 * which is defined for any alignment. `aot_mem_check` exposes an explicit
 * alignment predicate for callers that want to enforce a stricter policy;
 * the G2 fixtures exercise both aligned and unaligned accesses.
 *
 * Concurrency: this arena is single-threaded proof state. It makes no
 * stronger claim than that; there is no atomic/exclusive/concurrency model
 * (see docs/g2-aot-proof.md; atomics remain OPEN).
 */
#ifndef AOT_MEM_H
#define AOT_MEM_H

#include <stddef.h>
#include <stdint.h>

typedef enum {
    AOT_MEM_OK = 0,
    AOT_MEM_ERR_RANGE,   /* access outside [base, base+size) */
    AOT_MEM_ERR_ALIGN,   /* caller demanded alignment and it was violated */
    AOT_MEM_ERR_WIDTH    /* unsupported access width */
} AotMemStatus;

typedef struct AotMem {
    uint8_t *base;        /* host allocation (NULL => invalid arena) */
    uint64_t size;        /* bytes (> 0) */
    uint64_t guest_base;  /* guest address of base (evidence only) */
} AotMem;

/* Initialize an arena. Returns AOT_MEM_OK only when the arena is well formed:
 *   - `base` is non-NULL and `size` is non-zero;
 *   - `guest_base + size` does NOT overflow the 64-bit guest address space
 *     (otherwise addresses above the base would silently under-cover).
 * The caller guarantees `base` points at an allocation of at least `size`
 * bytes; this module never allocates and never assumes a guest address is a
 * host pointer. On failure the fields are left zeroed and every access is
 * rejected by aot_mem_check. */
AotMemStatus aot_mem_init(AotMem *m, uint8_t *base, uint64_t size,
                          uint64_t guest_base);

/* Bounds check only. Returns OK when [addr, addr+n) is inside the arena.
 * `n == 0` is OK only when addr is within [base, base+size] (so an
 * end-of-arena address is accepted for zero-length queries). */
AotMemStatus aot_mem_check(const AotMem *m, uint64_t addr, uint64_t n);

/* Alignment predicate: 1 when addr is a multiple of `align` (align a power
 * of two, 1..16). It does NOT imply the access is in range. */
int aot_mem_is_aligned(uint64_t addr, uint64_t align);

/* Little-endian loads. On any non-OK status the value written to *out is
 * undefined, but no memory outside the arena is touched. */
AotMemStatus aot_mem_ld8(const AotMem *m, uint64_t addr, uint8_t *out);
AotMemStatus aot_mem_ld16(const AotMem *m, uint64_t addr, uint16_t *out);
AotMemStatus aot_mem_ld32(const AotMem *m, uint64_t addr, uint32_t *out);
AotMemStatus aot_mem_ld64(const AotMem *m, uint64_t addr, uint64_t *out);
AotMemStatus aot_mem_ld128(const AotMem *m, uint64_t addr, uint64_t out[2]);

/* Little-endian stores. */
AotMemStatus aot_mem_st8(AotMem *m, uint64_t addr, uint8_t v);
AotMemStatus aot_mem_st16(AotMem *m, uint64_t addr, uint16_t v);
AotMemStatus aot_mem_st32(AotMem *m, uint64_t addr, uint32_t v);
AotMemStatus aot_mem_st64(AotMem *m, uint64_t addr, uint64_t v);
AotMemStatus aot_mem_st128(AotMem *m, uint64_t addr, const uint64_t v[2]);

/* Signed little-endian loads with sign extension (LDRSB/LDRSH/LDRSW). */
AotMemStatus aot_mem_lds8(const AotMem *m, uint64_t addr, int64_t *out);
AotMemStatus aot_mem_lds16(const AotMem *m, uint64_t addr, int64_t *out);
AotMemStatus aot_mem_lds32(const AotMem *m, uint64_t addr, int64_t *out);

/* Deterministic FNV-1a of the arena: a QUICK fixture checksum for the
 * differential harness. It is NOT an exact-version or provenance proof;
 * provenance identity is the SHA-256 generated by the offline Python
 * translator (see the CFG manifest). */
uint64_t aot_mem_fnv1a(const AotMem *m);

#endif /* AOT_MEM_H */
